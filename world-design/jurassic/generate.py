#!/usr/bin/env python3
"""Validate/compile shared definitions. World blocks are written only by Paper."""
import argparse
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def identity(config, landmarks):
    return hashlib.sha256(json.dumps([config, landmarks], sort_keys=True,
                                    separators=(",", ":")).encode()).hexdigest()


def implementation_identity():
    code=ROOT / "jurassic-plugin/src/main/java/de/ark/jurassic"
    return hashlib.sha256(b"".join((code / name).read_bytes() for name in
        ("Terrain.java", "Structures.java", "JurassicGenerator.java"))).hexdigest()


def validate(config, landmarks):
    if config["world"] != "jurassic_archipelago" or config["profile"] != "classic_adventure":
        raise ValueError("Only the separate classic_adventure test world is implemented")
    if config["border"] != {"center": [0, 0], "size": 32768}:
        raise ValueError("The archipelago requires its explicit 32768 border")
    islands = config["islands"]
    expected = {"sorna", "nublar", "matanceros", "muerta", "pena", "tacano"}
    if {i["id"] for i in islands} != expected or len(islands) != 6:
        raise ValueError("Exactly the six named islands are required")
    ids = set()
    for island in islands:
        if len(island["polygon"]) < 12:
            raise ValueError("Coast needs an individual outline")
        for x, z in island["polygon"]:
            if not (-16384 < x < 16384 and -16384 < z < 16384):
                raise ValueError("Island outside border")
    for site in landmarks["landmarks"]:
        if site["id"] in ids or site["island"] not in expected:
            raise ValueError("Duplicate site or unknown island")
        ids.add(site["id"])
        if site["profile"] != "classic_adventure":
            raise ValueError("Overlapping historical states require a separate world profile")
        if not site["source_ids"] or not site["access"]:
            raise ValueError("Every site requires provenance and access")
        x, z = site["position"]
        width, depth = site["extent"]
        if width <= 0 or depth <= 0 or abs(x) + width / 2 >= 16384 or abs(z) + depth / 2 >= 16384:
            raise ValueError("Unsafe landmark footprint")
    galli = next(s for s in landmarks["landmarks"] if s["id"] == "nublar_gallimimus")
    if galli["island"] != "nublar" or len(galli["cameras"]) != 5:
        raise ValueError("1993 Gallimimus scene belongs on Nublar with five cameras")


def load():
    config = json.loads((HERE / "archipelago.json").read_text())
    sites = json.loads((HERE / "landmarks.json").read_text())
    validate(config, sites)
    return config, sites


def java_source(config, landmarks):
    q = json.dumps
    def points(values):
        return "new int[][]{" + ",".join("{" + f"{x},{z}" + "}" for x, z in values) + "}"
    islands = []
    for i in config["islands"]:
        ridges = ",".join(f'new Terrain.Ridge({points(r["points"])},{r["height"]},{r["width"]})' for r in i["ridges"])
        rivers = ",".join(f'new Terrain.River({points(r["points"])},{r["width"]})' for r in i["rivers"])
        islands.append(f'new Terrain.Island({q(i["id"])},{q(i["style"])},{points(i["polygon"])},new Terrain.Ridge[]{{{ridges}}},new Terrain.River[]{{{rivers}}})')
    sites = []
    for s in landmarks["landmarks"]:
        if s.get("parent_id"):
            continue
        x, z = s["position"]
        w, d = s["extent"]
        sites.append(f'new Terrain.Site({q(s["id"])},{q(s["kind"])},{x},{z},{w},{d},{s["rotation"]},{points(s["access"])})')
    implementation=implementation_identity()
    b=config["reference_bounds"]
    reference=[b[k]//16 for k in ("min_x","min_z","max_x","max_z")]
    return ('// Generated by world-design/jurassic/generate.py compile; do not edit.\n'
            'package de.ark.jurassic;\nfinal class TerrainData {\n'
            f'    static final String HASH = {q(identity(config, landmarks))};\n'
            f'    static final String IMPLEMENTATION = {q(implementation)};\n'
            '    static final int[] REFERENCE = {'+','.join(map(str,reference))+'};\n'
            f'    static final String VERSION = {q(str(config["generator_version"]))};\n'
            f'    static final String WORLD = {q(config["world"])};\n'
            f'    static final long SEED = {config["seed"]}L;\n'
            f'    static final int SEA = {config["sea_level"]};\n'
            '    static final Terrain.Island[] ISLANDS = {\n        ' + ',\n        '.join(islands) + '\n    };\n'
            '    static final Terrain.Site[] SITES = {\n        ' + ',\n        '.join(sites) + '\n    };\n}\n')


def manifest(config, landmarks):
    return {"format": 1, "world": config["world"], "seed": config["seed"],
            "profile": config["profile"], "generator_version": config["generator_version"],
            "definition_sha256": identity(config, landmarks), "border": config["border"],
            "implementation_sha256": implementation_identity(),
            "full_square_chunks": 4194304, "generated_regions": [], "accepted_regions": [],
            "islands": [{"id": i["id"], "status": "planned"} for i in config["islands"]],
            "landmarks": [{"id": s["id"], "status": "planned"} for s in landmarks["landmarks"]],
            "previous_world_release": "world-2026-11-06", "acceptance": "pending"}


def coverage_manifest(config,sites,receipt):
    initial=receipt.get("initial",{})
    full=receipt.get("full_chunk_validation",{})
    b=config["reference_bounds"]
    bounds=[b["min_x"],b["min_z"],b["max_x"]+1,b["max_z"]+1]
    if (receipt.get("passed") is not True or initial.get("definition_sha256")!=identity(config,sites)
            or initial.get("implementation_sha256")!=implementation_identity()
            or full.get("status")!="passed" or full.get("verified_chunks")!=16384 or full.get("bounds")!=bounds):
        raise ValueError("A matching, exhaustively verified native reference receipt is required")
    result=manifest(config,sites)
    result["generated_regions"]=[{"id":"nublar_reference","bounds":b,"full_chunks":16384,
                                  "validation":"native_saved_full_chunks","accepted":False}]
    generated=set()
    for site in sites["landmarks"]:
        x,z=site["position"];w,d=site["extent"]
        if b["min_x"]<=x-w/2 and x+w/2<=b["max_x"] and b["min_z"]<=z-d/2 and z+d/2<=b["max_z"]:
            generated.add(site["id"])
    for site in result["landmarks"]:
        if site["id"] in generated: site["status"]="generated"
    for island in result["islands"]:
        if island["id"]=="nublar": island["status"]="partially_generated"
    result["artifacts"]=[receipt[k] for k in ("generation_archive","isolated_save_archive","archive","complete_save_archive") if k in receipt]
    result["native_plugin_sha256"]=receipt["inputs"]["plugin_sha256"]
    if "delivered_plugin_sha256" in receipt:
        result["delivered_plugin_sha256"]=receipt["delivered_plugin_sha256"]
    result["limitations"]=["Film likeness and official-client/device acceptance remain pending.",
                            "Only the reference rectangle is generated; outer islands and other sites are planned.",
                            "Dynamic dinosaur encounters are not baked into the terrain archive."]
    return result


def export(config,sites,receipt_path,destination):
    import native_render
    receipt=json.loads(receipt_path.read_text())
    state=coverage_manifest(config,sites,receipt)
    world=Path(receipt["initial"]["world_folder"])
    if not (world / "region").is_dir():
        raise ValueError("Receipt's saved region source is unavailable")
    destination.mkdir(parents=True,exist_ok=False)
    atlas=destination / "plugins/ArkAtlas/jurassic_archipelago"
    panel=destination / "admin-map"
    atlas.mkdir(parents=True);panel.mkdir()
    generated={s["id"] for s in state["landmarks"] if s["status"]=="generated"}
    lines=["world: jurassic_archipelago","origin-x: 0","origin-z: 0","extent: 16384",
           "zoom-divisors: [1, 4, 8]","sites:"]
    for site in sites["landmarks"]:
        if site["id"] in generated:
            lines.extend(["  - id: "+json.dumps(site["id"]),"    name: "+json.dumps(site["name"]),
                          "    type: dino",
                          "    x: "+str(site["position"][0]),"    z: "+str(site["position"][1])])
    (atlas / "sites.yml").write_text("\n".join(lines)+"\n")
    report=native_render.render(world / "region",atlas / "terrain.png",size=32768,resolution=1024,allow_partial=True)
    report["output"]="terrain.png"
    (atlas / "terrain-report.json").write_text(json.dumps(report,indent=2)+"\n")
    report=native_render.render(world / "region",panel / "jurassic_archipelago.png",size=2048,resolution=512,
                                center_x=8192,center_z=3072,verify_all_chunks=True)
    if report["status"]!="passed":
        raise ValueError("Saved native reference changed after its receipt")
    b=config["reference_bounds"]
    (panel / "worlds.json").write_text(json.dumps({"worlds":[{
        "id":"minecraft:jurassic_archipelago","name":"Jurassic Archipelago (reference)",
        "min_x":-16384,"max_x":16384,"min_z":-16384,"max_z":16384,
        "terrain_bounds":{"min_x":b["min_x"],"max_x":b["max_x"]+1,"min_z":b["min_z"],"max_z":b["max_z"]+1}}]},indent=2)+"\n")
    (destination / "quest-landmarks.json").write_text(json.dumps({"world":config["world"],"landmarks":[
        s for s in sites["landmarks"] if s["id"] in generated]},indent=2)+"\n")
    (destination / "world-manifest.json").write_text(json.dumps(state,indent=2)+"\n")
    print("Exported actual native coverage, atlas, panel and quest landmark data to "+str(destination))


def compile_definitions():
    config, landmarks = load()
    target = ROOT / "jurassic-plugin/src/main/java/de/ark/jurassic/TerrainData.java"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(java_source(config, landmarks))
    resources = ROOT / "jurassic-plugin/src/main/resources"
    resources.mkdir(parents=True, exist_ok=True)
    for name in ("archipelago.json", "landmarks.json"):
        (resources / name).write_bytes((HERE / name).read_bytes())
    print(f"Compiled {len(landmarks['landmarks'])} shared sites; definitions {identity(config, landmarks)}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["plan", "compile", "export"])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--receipt", type=Path)
    args = parser.parse_args()
    config, sites = load()
    if args.action == "compile":
        compile_definitions()
    elif args.action=="export":
        if not args.output or not args.receipt:
            parser.error("export requires --output NEW_DIRECTORY and --receipt NATIVE_REPORT")
        export(config,sites,args.receipt,args.output)
    else:
        content = json.dumps(manifest(config, sites), indent=2) + "\n"
        if args.output:
            with args.output.open("x") as stream:
                stream.write(content)
        else:
            print(content, end="")


if __name__ == "__main__":
    main()
